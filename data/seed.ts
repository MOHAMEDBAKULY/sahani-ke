function blocks(en: string[], ar: string[]): Localized<PortableBlock[]> {
  const toBlocks = (paras: string[]): PortableBlock[] =>
    paras.map((p) => {
      if (p.startsWith("## ")) {
        return { _type: "block", style: "h2", children: [{ _type: "span", text: p.slice(3) }] };
      }
      if (p.startsWith("> ")) {
        return { _type: "block", style: "blockquote", children: [{ _type: "span", text: p.slice(2) }] };
      }
      return { _type: "block", style: "normal", children: [{ _type: "span", text: p }] };
    });
  return { en: toBlocks(en), ar: toBlocks(ar) };
}

